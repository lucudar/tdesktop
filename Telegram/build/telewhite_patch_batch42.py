def write_build_info(root):
    '''The commit Telewhite is built from, the updates compare with it.'''
    sha = ''
    try:
        sha = subprocess.run(
            ['git', '-C', root, 'rev-parse', '--short=10', 'HEAD'],
            capture_output=True, check=True, text=True).stdout.strip()
    except Exception:
        sha = ''
    content = (
        '// Generated by Telegram/build/telewhite_patch_batch42.py.\n'
        '#pragma once\n\n'
        '#define TELEWHITE_SOURCE_SHA "' + sha + '"\n')
    path = os.path.join(root, BUILD_INFO)
    try:
        with open(path, 'r', encoding='utf-8') as f:
            if f.read() == content:
                return
    except OSError:
        pass
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(content)


